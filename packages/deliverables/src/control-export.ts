import { createHash } from 'node:crypto';
import {
  CONTROL_EXPORT_CONTRACT,
  CONTROL_EXPORT_VERSION,
  GovernanceExport,
  type GovernanceExport as GovernanceExportT,
} from '@aifit/control-export-contract';
import type { BlueprintBundle } from './blueprint.js';
import { findSecrets } from './secrets.js';

const AGENT_PATTERNS = new Set(['bounded-agent', 'autonomous-agent', 'llm-workflow']);
const REDACT = ['pii', 'sensitive_pii', 'phi', 'pci', 'financial', 'trade_secret', 'minors'];

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9_.-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80) || 'item';

export const EXPORT_DISCLAIMER =
  'Recommendations generated by AI Fit Teams from one assessment. Nothing here is an enforced control, a compliance attestation, or a measurement. Each item needs a human decision before it is adopted.';

/**
 * Derive the governance export from a blueprint bundle. Deterministic: every
 * item comes from the security rubric, the decision rules or the evaluation
 * plan, and says which.
 */
export function buildControlExport(bundle: BlueprintBundle): GovernanceExportT {
  const { blueprint: b, assessment: a } = bundle;
  const w = a.workload;

  const governanceRequirements: GovernanceExportT['governanceRequirements'] = [
    ...a.security.controls.map((c) => ({
      id: slug(c.id),
      requirement: c.requirement,
      rationale: c.why,
      severity: c.blocking ? ('blocking' as const) : ('recommended' as const),
      source: 'security-rubric' as const,
      verification: { method: c.verifiedBy, owner: 'customer' as const },
    })),
    ...b.decision.requiredControls.map((text, i) => ({
      id: `decision.${i + 1}`,
      requirement: text,
      rationale: 'Required by the deterministic decision rules for this workload.',
      severity: 'recommended' as const,
      source: 'decision-rules' as const,
      verification: { method: 'Confirm in the launch review that this is in place.', owner: 'customer' as const },
    })),
    ...a.evaluation.metrics.filter((m) => m.blocksLaunch).map((m, i) => ({
      id: `eval.${i + 1}`,
      requirement: `Meet "${m.name}" at ${m.threshold} before launch.`,
      rationale: 'A launch-blocking acceptance criterion from the evaluation plan.',
      severity: 'blocking' as const,
      source: 'evaluation-plan' as const,
      verification: { method: m.measuredHow, owner: 'customer' as const },
    })),
  ];

  const policySuggestions: GovernanceExportT['policySuggestions'] = [];
  const gated = w.actions.filter((x) => x.blastRadius === 'irreversible' || x.blastRadius === 'costly');
  if (gated.length) {
    policySuggestions.push({
      id: 'approve-consequential-actions',
      title: 'Human approval for consequential actions',
      rule: { kind: 'require_human_approval', actions: gated.map((x) => `${x.system}:${x.name}`) },
      rationale: 'These actions are costly or irreversible. A person approves each call before it runs.',
      status: 'suggested',
    });
  }
  const redact = w.dataClasses.filter((d) => REDACT.includes(d));
  if (redact.length) {
    policySuggestions.push({
      id: 'redact-sensitive-data',
      title: 'Redact sensitive data before prompts are built',
      rule: { kind: 'redact_data_classes', dataClasses: redact },
      rationale: 'Sensitive data classes are in scope; tokenise or redact them before any model sees them.',
      status: 'suggested',
    });
  }
  if (w.dataClasses.includes('credentials')) {
    policySuggestions.push({
      id: 'deny-credentials',
      title: 'Never send credentials to a model',
      rule: { kind: 'deny_data_classes', dataClasses: ['credentials'] },
      rationale: 'Keys, tokens and passwords must be vaulted, not prompted.',
      status: 'suggested',
    });
  }
  if (a.model) {
    const cap = Math.ceil((a.cost.perMonth.high ?? a.cost.perMonth.value) * 1.5);
    if (cap > 0) {
      policySuggestions.push({
        id: 'monthly-spend-cap',
        title: 'Monthly model spend cap',
        rule: { kind: 'monthly_spend_cap', usd: cap, basis: a.cost.perMonth.basis },
        rationale: `1.5× the upper estimate of monthly run cost (${a.cost.perMonth.basis}). Revisit once real spend is measured.`,
        status: 'suggested',
      });
    }
  }
  if (AGENT_PATTERNS.has(a.architecture.pattern) && a.callShape.turnsPerOutcome > 0) {
    policySuggestions.push({
      id: 'turn-cap',
      title: 'Cap model turns per outcome',
      rule: { kind: 'turn_cap', maxTurnsPerOutcome: Math.max(1, Math.ceil(a.callShape.turnsPerOutcome * 2)) },
      rationale: 'Twice the assumed turns per outcome for this pattern; stops runaway loops.',
      status: 'suggested',
    });
  }
  if (w.dataResidency !== 'any') {
    policySuggestions.push({
      id: 'data-residency',
      title: 'Keep processing in the required region',
      rule: { kind: 'data_residency', region: w.dataResidency },
      rationale: 'The intake states a data residency constraint.',
      status: 'suggested',
    });
  }
  if (w.actions.length && AGENT_PATTERNS.has(a.architecture.pattern)) {
    policySuggestions.push({
      id: 'tool-allow-list',
      title: 'Restrict the agent to these tools',
      rule: { kind: 'tool_allow_list', tools: w.actions.map((x) => `${x.system}:${x.name}`) },
      rationale: 'Only the actions named in the assessment; anything else is denied.',
      status: 'suggested',
    });
  }

  const inventoryRequired = AGENT_PATTERNS.has(a.architecture.pattern) || (w.actions.length > 0 && w.autonomy !== 'suggest');
  const doc: GovernanceExportT = {
    contract: CONTROL_EXPORT_CONTRACT,
    version: CONTROL_EXPORT_VERSION,
    enforcement: 'recommended-not-enforced',
    disclaimer: EXPORT_DISCLAIMER,
    source: {
      product: 'AI Fit Teams',
      generatedAt: b.meta.generatedAt,
      assessment: b.meta.assessment,
      inputHash: b.meta.decisionInputHash,
      engines: b.meta.engines,
    },
    workload: {
      name: w.name.slice(0, 200),
      verdict: a.suitability.verdict,
      outcome: b.decision.outcome,
      pattern: a.architecture.pattern,
      dataClasses: [...w.dataClasses],
      regulated: w.regulated.filter((r) => r !== 'none'),
      riskLevel: a.security.level,
    },
    governanceRequirements,
    policySuggestions,
    agentInventory: {
      required: inventoryRequired,
      reason: inventoryRequired
        ? 'The recommended pattern takes actions or chains model calls, so it should be registered and owned as an agent.'
        : 'No agent behaviour: the recommended pattern does not act on its own.',
      entries: inventoryRequired
        ? [{
            name: w.name.slice(0, 160),
            pattern: a.architecture.pattern,
            autonomy: w.autonomy,
            modelId: a.model?.primary.id ?? null,
            dataClasses: [...w.dataClasses],
            tools: w.actions.map((x) => ({
              name: x.name,
              system: x.system,
              write: x.write,
              blastRadius: x.blastRadius,
              approvalRequired: x.blastRadius === 'irreversible' || x.blastRadius === 'costly',
            })),
            owner: null,
          }]
        : [],
    },
    evaluationEvidence: {
      status: a.evaluation.metrics.length ? 'planned' : 'not-applicable',
      kind: a.evaluation.kind,
      goldenSetSize: a.evaluation.goldenSetSize,
      acceptanceCriteria: a.evaluation.metrics,
      observed: [],
      note: 'This is the evaluation plan. AI Fit has not run any evaluation; observed results come from Control telemetry once the workload is live.',
    },
  };
  return GovernanceExport.parse(doc);
}

export function renderControlExport(doc: GovernanceExportT): { filename: string; contentType: string; body: string; idempotencyKey: string } {
  const parsed = GovernanceExport.safeParse(doc);
  if (!parsed.success) throw new Error('Governance export does not match its contract.');
  const body = JSON.stringify(parsed.data, null, 2) + '\n';
  const leaked = findSecrets(body);
  if (leaked.length) throw new Error(`Governance export contains credential-like content (${leaked.join(', ')}).`);
  return { filename: 'governance-export.json', contentType: 'application/json; charset=utf-8', body, idempotencyKey: createHash('sha256').update(body).digest('hex') };
}

// --- Adapter boundary ------------------------------------------------------------

export interface DeliveryResult {
  delivered: boolean;
  adapter: string;
  detail: string;
}

export interface ControlExportAdapter {
  readonly name: string;
  deliver(doc: GovernanceExportT): Promise<DeliveryResult>;
}

/**
 * HTTP delivery to a Control endpoint the operator configures. The endpoint is
 * part of a proposed contract (CONTRACT.md); nothing here assumes it exists,
 * and every non-2xx answer is reported as "not delivered".
 */
export function httpControlAdapter(url: string, token: string | undefined, fetchImpl: typeof fetch = fetch, timeoutMs = 5000): ControlExportAdapter {
  return {
    name: 'http',
    async deliver(doc) {
      const { body, idempotencyKey } = renderControlExport(doc);
      const ac = new AbortController();
      const timer = setTimeout(() => ac.abort(), timeoutMs);
      try {
        const res = await fetchImpl(url, {
          method: 'POST',
          headers: {
            'content-type': 'application/vnd.aifit.governance-export+json; version=1',
            'idempotency-key': idempotencyKey,
            ...(token ? { authorization: `Bearer ${token}` } : {}),
          },
          body,
          signal: ac.signal,
        });
        if (res.status === 202 || res.status === 200 || res.status === 201) return { delivered: true, adapter: 'http', detail: `Control accepted the export (${res.status}). It is a recommendation awaiting review there.` };
        if (res.status === 409) return { delivered: true, adapter: 'http', detail: 'Control already has this export.' };
        return { delivered: false, adapter: 'http', detail: `Control answered ${res.status}. Download the file and import it instead.` };
      } catch {
        return { delivered: false, adapter: 'http', detail: 'Control could not be reached. Download the file and import it instead.' };
      } finally {
        clearTimeout(timer);
      }
    },
  };
}

/** Null unless CONTROL_EXPORT_URL is set and https (or localhost for development). */
export function controlAdapterFromEnv(env: Record<string, string | undefined>, fetchImpl?: typeof fetch): ControlExportAdapter | null {
  const url = env.CONTROL_EXPORT_URL?.trim();
  if (!url) return null;
  let parsed: URL;
  try { parsed = new URL(url); } catch { return null; }
  const local = parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1';
  if (parsed.protocol !== 'https:' && !(local && parsed.protocol === 'http:')) return null;
  return httpControlAdapter(parsed.toString(), env.CONTROL_EXPORT_TOKEN?.trim() || undefined, fetchImpl);
}
